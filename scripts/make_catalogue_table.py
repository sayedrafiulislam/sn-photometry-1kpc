"""
make_catalogue_table.py  (read-only on results; writes one .tex file)

Writes the rows of Appendix A (Table A.1) to results/tables/catalogue_rows.tex,
ready for \\input inside the thesis longtable. Re-run after any pipeline
rerun so the appendix always matches the catalogue. Place in scripts/.
"""
from pathlib import Path
import pandas as pd

REPO = next(p for p in Path(__file__).resolve().parents
            if (p / "results").is_dir())
IN_PATH = REPO / "results" / "phase5_calibration" / "calibrated_colour_1kpc_dered.csv"
OUT_DIR = REPO / "results" / "tables"
OUT_PATH = OUT_DIR / "catalogue_rows.tex"

COLS = ["object", "z", "mag_B_dered", "mag_V_dered",
        "B_minus_V_dered", "B_minus_V_dered_err", "ebv_sfd"]

if not IN_PATH.exists():
    raise SystemExit(f"STOP: missing input {IN_PATH}")
d = pd.read_csv(IN_PATH)
missing = [c for c in COLS + ["flag_exclude"] if c not in d.columns]
if missing:
    raise SystemExit(f"STOP: columns missing from {IN_PATH.name}: {missing}")

kept = d[~d["flag_exclude"].astype(bool)].sort_values("object")
if kept[COLS].isna().any().any():
    bad = kept.loc[kept[COLS].isna().any(axis=1), "object"].tolist()
    raise SystemExit(f"STOP: NaN values in kept objects: {bad}")


def tex_name(s):
    return str(s).replace("_", r"\_")


lines = [
    f"% Generated by make_catalogue_table.py from {IN_PATH.name}",
    f"% {len(kept)} objects. Do not edit by hand; re-run the script.",
]
for _, r in kept.iterrows():
    lines.append(
        f"{tex_name(r['object'])} & {r['z']:.4f} & {r['mag_B_dered']:.3f} & "
        f"{r['mag_V_dered']:.3f} & {r['B_minus_V_dered']:.3f} & "
        f"{r['B_minus_V_dered_err']:.3f} & {r['ebv_sfd']:.3f} \\\\"
    )

OUT_DIR.mkdir(parents=True, exist_ok=True)
OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {len(kept)} rows to {OUT_PATH}")
print(f"Excluded by quality criteria: {int(d['flag_exclude'].astype(bool).sum())}")
print("Check both numbers against the text of Appendix A.")